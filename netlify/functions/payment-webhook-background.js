import { getStore } from "@netlify/blobs";

export async function handler(event) {
  console.log("payment-webhook-background triggered");

  try {
    const params = new URLSearchParams(event.body);
    const paymentId = params.get("id");

    if (!paymentId) {
      console.error("No payment ID in webhook");
      return { statusCode: 200, body: "OK" };
    }

    const MOLLIE_API_KEY = process.env.MOLLIE_API_KEY;
    const mollieRes = await fetch(`https://api.mollie.com/v2/payments/${paymentId}`, {
      headers: { Authorization: `Bearer ${MOLLIE_API_KEY}` },
    });
    const payment = await mollieRes.json();

    console.log("Payment status:", payment.status);

    if (payment.status !== "paid") {
      return { statusCode: 200, body: "OK" };
    }

    const { email, reportType, blobKey } = payment.metadata || {};

    if (!email) {
      console.error("Missing email in metadata");
      return { statusCode: 200, body: "OK" };
    }

    const RESEND_API_KEY = process.env.RESEND_API_KEY;
    const ANTHROPIC_API_KEY = process.env.ANTHROPIC_API_KEY;

    // Send immediate thank you email
    console.log("Sending thank you email to:", email);
    await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${RESEND_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: "HealthDecoded <onboarding@resend.dev>",
        to: email,
        subject: "✅ Payment confirmed — Your report is being generated",
        html: `
          <div style="font-family:Arial,sans-serif;max-width:600px;margin:0 auto;padding:32px;color:#1e293b;">
            <div style="text-align:center;margin-bottom:32px;">
              <h1 style="color:#0ea5e9;font-size:28px;margin-bottom:8px;">Health<span style="color:#0f172a;">Decoded</span></h1>
            </div>
            <div style="background:#f0fdf4;border:2px solid #16a34a;border-radius:12px;padding:24px;margin-bottom:24px;text-align:center;">
              <div style="font-size:48px;margin-bottom:12px;">✅</div>
              <h2 style="color:#16a34a;font-size:22px;margin-bottom:8px;">Payment confirmed!</h2>
              <p style="color:#166534;font-size:15px;">Thank you! Your full health report is now being generated by our AI.</p>
            </div>
            <div style="background:#f0f9ff;border:1px solid #bae6fd;border-radius:10px;padding:20px;margin-bottom:24px;">
              <h3 style="color:#0369a1;margin-bottom:12px;">⏱️ What happens next?</h3>
              <p style="color:#374151;font-size:14px;line-height:1.7;">
                Our AI is analysing your ${reportType === "lab" ? "blood test results" : "health data"} in detail.
                This takes <strong>2–5 minutes</strong>.
                You will receive a <strong>second email</strong> with your complete report shortly.
              </p>
              <p style="color:#64748b;font-size:13px;margin-top:12px;">📧 Check your spam folder if you don't see it within 10 minutes.</p>
            </div>
            <div style="text-align:center;padding:16px;background:#f8fafc;border-radius:8px;">
              <p style="color:#64748b;font-size:12px;margin:0;">HealthDecoded · Educational content only · Not a medical device<br/>Always consult a qualified healthcare professional</p>
            </div>
          </div>
        `,
      }),
    });

    // Fetch PDF from Netlify Blobs
    if (!blobKey) {
      console.error("No blobKey in metadata");
      return { statusCode: 200, body: "OK" };
    }

    console.log("Fetching blob data for key:", blobKey);
    const store = getStore({ name: "report-data", consistency: "strong" });
    const blobData = await store.get(blobKey, { type: "json" });

    if (!blobData) {
      console.error("Blob not found for key:", blobKey);
      return { statusCode: 200, body: "OK" };
    }

    const { fileB64, fileType } = blobData;
    const isLab = reportType === "lab";

    // Call Claude to generate full report
    console.log("Calling Claude...");
    const messageContent = [];
    if (fileB64 && fileType) {
      if (fileType === "application/pdf") {
        messageContent.push({ type: "document", source: { type: "base64", media_type: "application/pdf", data: fileB64 } });
      } else {
        messageContent.push({ type: "image", source: { type: "base64", media_type: fileType, data: fileB64 } });
      }
    }

    const prompt = isLab
      ? `You are an expert clinical lab results interpreter. Analyse the attached blood test report and return a detailed plain-language interpretation with a 7-day meal plan.

Return ONLY this JSON:
{
  "labSummary": "string",
  "overallScore": 75,
  "biomarkers": [{"name":"string","value":"string","referenceRange":"string","optimalRange":"string","status":"optimal|normal|borderline|concerning|critical","category":"string","interpretation":"string"}],
  "keyFindings": ["string"],
  "recommendedTests": ["string"],
  "doctorTalkingPoints": ["string"],
  "retestPlan": {"timeframe":"string","reason":"string","markersToRetest":["string"],"expectedImprovements":"string"},
  "mealPlan": {
    "goal": "string",
    "keyNutrients": ["string"],
    "generalGuidelines": ["string"],
    "days": [
      {"day":1,"dayName":"Monday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":2,"dayName":"Tuesday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":3,"dayName":"Wednesday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":4,"dayName":"Thursday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":5,"dayName":"Friday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":6,"dayName":"Saturday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}},
      {"day":7,"dayName":"Sunday","breakfast":{"meal":"string","why":"string"},"lunch":{"meal":"string","why":"string"},"dinner":{"meal":"string","why":"string"},"snack":{"meal":"string","why":"string"}}
    ]
  }
}
Return ONLY valid JSON. No markdown.`
      : `Generate a health consultation report. Return ONLY valid JSON:
{
  "urgency": {"level":1,"label":"string","color":"green","message":"string","showActions":true},
  "summary": "string",
  "healthScore": {"metabolic":70,"weight":70,"sleep":70,"overall":70},
  "actionCards": [{"finding":"string","severity":"borderline","explanation":"string","actions":[{"type":"diet","title":"string","detail":"string","dose":"","doNotUseIf":[],"pharmacistNote":""}],"retestIn":"string"}],
  "concerns": [{"name":"string","confidence":"Medium","reasoning":"string"}],
  "suggestedTests": [{"test":"string","reason":"string"}],
  "doctorQuestions": ["string"],
  "homeEssentials": [{"item":"string","reason":"string"}]
}
Return ONLY valid JSON. No markdown.`;

    messageContent.push({ type: "text", text: prompt });

    const claudeRes = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: "claude-sonnet-4-6",
        max_tokens: 8000,
        messages: [{ role: "user", content: messageContent }],
      }),
    });

    const claudeData = await claudeRes.json();
    const reportText = claudeData.content.map((c) => c.text || "").join("");
    const report = JSON.parse(reportText.replace(/```json|```/g, "").trim());

    console.log("Report generated, sending email...");

    // Build email HTML
    let reportHtml = "";

    if (isLab && report.labSummary) {
      const statusColors = {
        optimal: { bg: "#dcfce7", color: "#16a34a", label: "Optimal" },
        normal: { bg: "#dbeafe", color: "#1d4ed8", label: "Normal" },
        borderline: { bg: "#fef9c3", color: "#ca8a04", label: "Borderline" },
        concerning: { bg: "#fff7ed", color: "#ea580c", label: "Concerning" },
        critical: { bg: "#fee2e2", color: "#dc2626", label: "Critical" },
      };
      const scoreCol = report.overallScore >= 70 ? "#16a34a" : report.overallScore >= 50 ? "#ca8a04" : "#dc2626";
      const scoreBg = report.overallScore >= 70 ? "#dcfce7" : report.overallScore >= 50 ? "#fef9c3" : "#fee2e2";
      const categories = [...new Set((report.biomarkers || []).map((b) => b.category))];

      let biomarkersHtml = "";
      categories.forEach((cat) => {
        biomarkersHtml += `<h3 style="color:#7c3aed;font-size:15px;margin:20px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">${cat}</h3>`;
        report.biomarkers.filter((b) => b.category === cat).forEach((b) => {
          const sc = statusColors[b.status] || statusColors.normal;
          biomarkersHtml += `
            <div style="border-radius:8px;border:1px solid #e2e8f0;margin-bottom:10px;overflow:hidden;">
              <div style="background:${sc.bg};padding:10px 14px;display:flex;justify-content:space-between;align-items:center;">
                <div>
                  <strong style="font-size:14px;color:#0f172a;">${b.name}</strong>
                  <span style="font-size:12px;color:#64748b;margin-left:10px;">Value: <strong style="color:${sc.color};">${b.value}</strong>${b.referenceRange ? ` · Ref: ${b.referenceRange}` : ""}${b.optimalRange ? ` · Optimal: ${b.optimalRange}` : ""}</span>
                </div>
                <span style="background:#fff;color:${sc.color};font-size:11px;font-weight:700;padding:2px 8px;border-radius:8px;">${sc.label}</span>
              </div>
              <div style="padding:10px 14px;font-size:13px;color:#374151;line-height:1.6;">${b.interpretation}</div>
            </div>`;
        });
      });

      let mealPlanHtml = "";
      if (report.mealPlan) {
        mealPlanHtml = `
          <h2 style="color:#16a34a;font-size:16px;margin:24px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">🥗 Your 7-Day Meal Plan</h2>
          <div style="background:#dcfce7;border-radius:8px;padding:10px 14px;margin-bottom:14px;font-size:13px;color:#166534;"><strong>Goal:</strong> ${report.mealPlan.goal}</div>
          ${(report.mealPlan.days || []).map((d) => `
            <div style="border:1px solid #bbf7d0;border-radius:8px;margin-bottom:8px;overflow:hidden;">
              <div style="background:#16a34a;padding:8px 12px;font-weight:700;font-size:13px;color:#fff;">Day ${d.day} — ${d.dayName}</div>
              <table style="width:100%;border-collapse:collapse;padding:10px;">
                ${[["🌅 Breakfast", d.breakfast], ["☀️ Lunch", d.lunch], ["🌙 Dinner", d.dinner], ["🍎 Snack", d.snack]].map(([lbl, data]) => data ? `
                  <tr><td style="padding:8px 12px;background:#f0fdf4;vertical-align:top;width:50%;">
                    <div style="font-size:11px;font-weight:700;color:#16a34a;">${lbl}</div>
                    <div style="font-size:12px;font-weight:600;color:#1e293b;">${data.meal}</div>
                    <div style="font-size:11px;color:#64748b;font-style:italic;">${data.why}</div>
                  </td></tr>` : "").join("")}
              </table>
            </div>`).join("")}`;
      }

      reportHtml = `
        <div style="background:${scoreBg};border:2px solid ${scoreCol};border-radius:12px;padding:20px;margin-bottom:20px;">
          <div style="display:flex;align-items:center;gap:16px;">
            <div style="width:60px;height:60px;border-radius:50%;background:#fff;border:3px solid ${scoreCol};display:flex;align-items:center;justify-content:center;font-size:20px;font-weight:800;color:${scoreCol};flex-shrink:0;">${report.overallScore}</div>
            <div>
              <div style="font-weight:700;font-size:15px;color:#0f172a;margin-bottom:6px;">Overall Health Score</div>
              <div style="font-size:13px;color:#374151;line-height:1.6;">${report.labSummary}</div>
            </div>
          </div>
        </div>
        ${report.keyFindings?.length ? `<h2 style="color:#0369a1;font-size:16px;margin:24px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">🎯 Key Findings</h2>${report.keyFindings.map((f, i) => `<div style="margin-bottom:8px;padding:8px 12px;background:#f0f9ff;border-left:3px solid #0ea5e9;border-radius:4px;font-size:13px;">${i + 1}. ${f}</div>`).join("")}` : ""}
        <h2 style="color:#7c3aed;font-size:16px;margin:24px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">🔬 Biomarker Analysis</h2>
        ${biomarkersHtml}
        ${report.retestPlan ? `<h2 style="color:#ca8a04;font-size:16px;margin:24px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">🔁 When to Retest</h2><div style="background:#fffbeb;border:1px solid #fde68a;border-radius:8px;padding:14px;"><div style="font-size:16px;font-weight:800;color:#ca8a04;margin-bottom:6px;">Recommended: ${report.retestPlan.timeframe}</div><div style="font-size:13px;margin-bottom:8px;">${report.retestPlan.reason}</div><div style="font-size:13px;"><strong>Expected improvements:</strong> ${report.retestPlan.expectedImprovements}</div></div>` : ""}
        ${mealPlanHtml}
        ${report.doctorTalkingPoints?.length ? `<h2 style="color:#0369a1;font-size:16px;margin:24px 0 10px;border-bottom:2px solid #e2e8f0;padding-bottom:6px;">💬 What to Discuss with Your Doctor</h2>${report.doctorTalkingPoints.map((q) => `<div style="font-size:13px;padding:8px 12px;background:#f0f9ff;border-radius:5px;border-left:3px solid #0ea5e9;margin-bottom:6px;">${q}</div>`).join("")}` : ""}
      `;
    } else {
      const urgColors = { green: { bg: "#dcfce7", border: "#16a34a", text: "#14532d" }, yellow: { bg: "#fef9c3", border: "#ca8a04", text: "#713f12" }, orange: { bg: "#fff7ed", border: "#ea580c", text: "#7c2d12" }, red: { bg: "#fee2e2", border: "#dc2626", text: "#7f1d1d" } };
      const uc = urgColors[report.urgency?.color] || urgColors.green;
      reportHtml = `
        <div style="background:${uc.bg};border:2px solid ${uc.border};border-radius:12px;padding:16px;margin-bottom:20px;">
          <div style="font-size:17px;font-weight:800;color:${uc.text};">Urgency Level ${report.urgency?.level}/5 — ${report.urgency?.label}</div>
          <div style="font-size:13px;color:${uc.text};line-height:1.6;margin-top:8px;">${report.urgency?.message}</div>
        </div>
        ${report.summary ? `<div style="background:#f0f9ff;border:1px solid #bae6fd;border-radius:10px;padding:14px;margin-bottom:16px;font-size:14px;color:#0369a1;line-height:1.6;">${report.summary}</div>` : ""}
        ${report.actionCards?.length ? `<h2 style="color:#0f172a;font-size:16px;margin:24px 0 10px;">🎯 Action Plan</h2>${report.actionCards.map((card) => `<div style="border:1px solid #e2e8f0;border-radius:10px;margin-bottom:12px;overflow:hidden;"><div style="background:#f8fafc;padding:10px 14px;font-weight:700;font-size:14px;">${card.finding}</div><div style="padding:10px 14px;font-size:13px;color:#374151;">${card.explanation}</div>${card.actions?.map((a) => `<div style="margin:0 14px 10px;background:#f0f9ff;border-radius:8px;padding:10px;"><div style="font-weight:700;font-size:13px;color:#0369a1;">${a.title}</div><div style="font-size:13px;">${a.detail}</div></div>`).join("") || ""}</div>`).join("")}` : ""}
        ${report.doctorQuestions?.length ? `<h2 style="color:#0369a1;font-size:16px;margin:24px 0 10px;">💬 Questions for Your Doctor</h2>${report.doctorQuestions.map((q) => `<div style="font-size:13px;padding:8px 12px;background:#f0f9ff;border-radius:5px;border-left:3px solid #0ea5e9;margin-bottom:6px;">${q}</div>`).join("")}` : ""}
      `;
    }

    await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${RESEND_API_KEY}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        from: "HealthDecoded <onboarding@resend.dev>",
        to: email,
        subject: `📊 Your HealthDecoded ${isLab ? "Blood Test Analysis" : "Health Consultation"} Report`,
        html: `
          <div style="font-family:Arial,sans-serif;max-width:700px;margin:0 auto;padding:32px;color:#1e293b;">
            <div style="text-align:center;margin-bottom:32px;">
              <h1 style="color:#0ea5e9;font-size:28px;margin-bottom:8px;">Health<span style="color:#0f172a;">Decoded</span></h1>
              <p style="color:#64748b;font-size:14px;">AI-powered health analysis — educational content only</p>
            </div>
            <div style="background:#fffbeb;border:1px solid #fde68a;border-radius:8px;padding:12px 16px;margin-bottom:24px;font-size:12px;color:#92400e;">
              <strong>Important:</strong> This report is AI-generated for educational purposes only. Not a medical diagnosis. Always consult a qualified healthcare professional.
            </div>
            <h2 style="color:#0f172a;font-size:20px;margin-bottom:20px;">Your ${isLab ? "Blood Test Analysis" : "Health Consultation"} Report</h2>
            ${reportHtml}
            <div style="margin-top:32px;padding:16px;background:#f1f5f9;border-radius:8px;font-size:11px;color:#64748b;text-align:center;">
              HealthDecoded · AI-generated educational content only · Not a medical device<br/>Always consult a qualified healthcare professional
            </div>
          </div>
        `,
      }),
    });

    console.log("Full report email sent to:", email);

    // Clean up blob
    try { await store.delete(blobKey); } catch (e) { console.log("Blob cleanup non-critical:", e.message); }

    return { statusCode: 200, body: "OK" };
  } catch (err) {
    console.error("payment-webhook-background error:", err);
    return { statusCode: 200, body: "OK" };
  }
}
